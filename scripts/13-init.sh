# OpenClaw completions — LAZY (2026-10-11).  The real definition is ~229 KB of bash
# (the CLI-generated ~/.openclaw/completions/openclaw.bash), and v16 removed the
# DUPLICATE of it — but that copy was still PARSED in every interactive shell for a
# completion set most shells never touch.  Define a tiny stand-in and register it for
# `openclaw`; the first TAB sources the real file (which defines the real
# `_openclaw_completion` AND re-registers `complete -F _openclaw_completion openclaw`,
# overwriting this registration) and then delegates to it.  So the parse cost moves
# from every shell start to the first completion use, and the completion behaviour is
# unchanged.  The stub has a UNIQUE name, so a failed source can never recurse — a
# shell with no completion file simply leaves TAB inert.
#
# Precedence is the same as v16: TAC_OC_COMPLETION_FILE, the CLI-generated copy, then
# the repo-versioned fallback (regenerated by tools/sync-openclaw-completion.sh).
__tac_oc_completion_stub() {
    local _oc_comp
    for _oc_comp in "${TAC_OC_COMPLETION_FILE:-}" \
                    "$HOME/.openclaw/completions/openclaw.bash" \
                    "$TACTICAL_REPO_ROOT/scripts/completions/openclaw.bash"
    do
        [[ -n "$_oc_comp" && -r "$_oc_comp" ]] || continue
        # shellcheck source=/dev/null
        source "$_oc_comp"
        break
    done
    # After the source the real function exists (and `complete` now points at it, so
    # this stub is not called again); delegate the TAB that triggered the load.  If no
    # file was readable, do nothing rather than error.
    if [[ "$(type -t _openclaw_completion)" == "function" ]]
    then
        _openclaw_completion "$@"
    fi
}
complete -F __tac_oc_completion_stub openclaw

