"""HTML template generation for the knowledge graph viewer.

The Cytoscape.js frontend template lives in ``templates/kgraph.html``.
This module loads it at import time and provides ``generate_html()``
to inject graph data and write the output file.
"""

from __future__ import annotations

import json
import logging
import os
import re
from html import escape as html_escape

from tools.fsutil import atomic_write_text

logger = logging.getLogger(__name__)

_TEMPLATE_PATH = os.path.join(os.path.dirname(__file__), "templates", "kgraph.html")


def _load_template() -> str:
    try:
        with open(_TEMPLATE_PATH, "r", encoding="utf-8") as f:
            return f.read()
    except OSError as exc:
        # A packaging regression here renders a broken viewer; log loudly so
        # it is not mistaken for a normal "empty graph" page.
        logger.error("kgraph viewer template missing or unreadable at %s: %s", _TEMPLATE_PATH, exc)
        return "<html><body><h1>Template not found</h1><p>Expected at %s</p></body></html>" % _TEMPLATE_PATH


HTML_TMPL = _load_template()


def ensure_parent_dir(path: str) -> None:
    parent = os.path.dirname(os.path.abspath(os.path.expanduser(path)))
    if parent:
        os.makedirs(parent, exist_ok=True)


def _report_html(report_text: str) -> str:
    """Render the narrative report as a minimal, escaped HTML block.

    A tiny renderer rather than a markdown dependency: the report is generated by this
    package, so its shapes are known (h1/h2, `- ` bullets, `**bold**`, `` `code` ``).
    Everything is escaped FIRST, so a label containing `<` cannot inject markup.
    """
    out: list[str] = ['<section id="kgraph-report">']
    in_list = False

    def _close_list() -> None:
        nonlocal in_list
        if in_list:
            out.append("</ul>")
            in_list = False

    for raw in report_text.splitlines():
        line = html_escape(raw, quote=False)
        line = re.sub(r"\*\*(.+?)\*\*", r"<strong>\1</strong>", line)
        line = re.sub(r"`([^`]+)`", r"<code>\1</code>", line)
        if line.startswith("## "):
            _close_list()
            out.append(f"<h3>{line[3:]}</h3>")
        elif line.startswith("# "):
            _close_list()
            out.append(f"<h2>{line[2:]}</h2>")
        elif line.startswith("- "):
            if not in_list:
                out.append("<ul>")
                in_list = True
            out.append(f"<li>{line[2:]}</li>")
        elif not line.strip():
            _close_list()
        else:
            _close_list()
            out.append(f"<p>{line}</p>")
    _close_list()
    out.append("</section>")
    return "\n".join(out)


def generate_html(graph: dict, outpath: str, report_text: str | None = None) -> None:
    # The payload is embedded inside a <script> element.  Escape the
    # characters that could terminate that element (`</script>`, `<!--`);
    # the \uXXXX escapes keep the literal valid JSON for the JS parser.
    payload = json.dumps(graph).replace("<", "\\u003c").replace(">", "\\u003e").replace("&", "\\u0026")
    html = HTML_TMPL.replace("%s", payload, 1)
    # The narrative travels WITH the page (2026-11-27): the report and the viewer were
    # separate artefacts, so the summary, god nodes and suggested questions were only
    # visible in a markdown file nobody opened beside the graph.
    if report_text:
        block = _report_html(report_text)
        html = html.replace("</body>", block + "\n</body>", 1) if "</body>" in html else html + block
    atomic_write_text(os.path.expanduser(outpath), html)
